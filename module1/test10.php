<?php
// switch statement
$day = "D";
switch ($day) {
    case "A":
        echo "Today is Monday <br>";
        break;
    case "B":
        echo "Today is Tuesday <br>";
        break;
    case "C":
        echo "Today is Wednesday <br>";
        break;
    case "D":
        echo "Today is Thursday <br>";
        break;
    case "E":
        echo "Today is Friday <br>";
        break;
    case "F":
        echo "Today is Saturday <br>";
        break;
    case "G":
        echo "Today is Sunday <br>";
        break;
    default:
        echo "Invalid day <br>";
}
?>