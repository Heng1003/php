<?php
// comparison operator
$x = 10;
$y = 20;

echo "x == y: " . ($x == $y ? "true" : "false") . "<br>";  // false
echo "x != y: " . ($x != $y ? "true" : "false") . "<br>";  // true
echo "x < y: " . ($x < $y ? "true" : "false") . "<br>";   // true
echo "x > y: " . ($x > $y ? "true" : "false") . "<br>";   // false
echo "x <= y: " . ($x <= $y ? "true" : "false") . "<br>";  // true
echo "x >= y: " . ($x >= $y ? "true" : "false") . "<br>";  // false

?>