<?php
// if statement
$x = 10;
$y = 20;
if ($x < $y) {
    echo "x is less than y <br>";
}
// if else statement
if($x > $y) {
    echo "x is greater than y <br>";
} else {
    echo "x is not greater than y <br>";
}
// if else if statement
if($x == $y) {
    echo "x is equal to y <br>";
} elseif($x < $y) {
    echo "x is less than y <br>";
} else {
    echo "x is greater than y <br>";
}
?>